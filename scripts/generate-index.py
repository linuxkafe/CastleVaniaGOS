#!/usr/bin/env python3
"""
Generate aes/INDEX.md from shadow-doc frontmatter + scoring.

Marker-delimited like kanban: <!-- INDEX_START --> / <!-- INDEX_END -->.
"""

import re
import sys
import os
import yaml
from pathlib import Path
from datetime import datetime, timezone

AES_ROOT = Path(__file__).resolve().parent.parent
SHADOW_DIR = AES_ROOT / "aes" / "shadow"
ACCESS_LOG = AES_ROOT / "aes" / "shadow" / "access.log"
INDEX_FILE = AES_ROOT / "aes" / "INDEX.md"

TOKEN_ESTIMATE_PER_ENTRY = 80  # approx tokens per index line

# A line of INDEX.md that carries a shadow-doc entry. Used by check() to size
# each entry individually. Anchored on the id rather than on the table shape:
# the index is Markdown with a table, and a shape-based match would break the
# day someone adds a section.
SD_ENTRY_RE = re.compile(r"\|\s*\*?\*?SD-[A-Za-z0-9-]+")
TOKEN_BUDGET = DEFAULT_TOKEN_BUDGET = 4000

sys.path.insert(0, str(AES_ROOT))
from lib.memory.scoring import (
    CONFIG,
    compute_activation,
    compute_centrality,
    composite_score,
    parse_access_log,
)


def extract_frontmatter(path: Path) -> dict:
    content = path.read_text()
    if not content.startswith("---"):
        return {}
    _, fm_str, _ = content.split("---", 2)
    try:
        return yaml.safe_load(fm_str) or {}
    except yaml.YAMLError:
        return {}


def mark_synthesis(sid: str) -> None:
    """Write /synthesis marker to access.log for a shadow doc via canonical writer."""
    import subprocess
    writer = AES_ROOT / "scripts" / "write-access-log.sh"
    if writer.exists():
        subprocess.run([str(writer), sid, "/synthesis"], check=False)
    else:
        # Fallback: direct write (pre-migration)
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S%z")
        with open(ACCESS_LOG, "a") as f:
            f.write(f"{ts} {sid} /synthesis\n")


def generate():
    accesses = parse_access_log(ACCESS_LOG)
    now = datetime.now(timezone.utc)
    entries = []

    # Build dependencies from graph for centrality computation
    try:
        from lib.epistemic.cold_retrieval import build_shadow_graph
        adj = build_shadow_graph()
        dependencies = {node: list(neighbors) for node, neighbors in adj.items()}
    except (ImportError, Exception):
        dependencies = None

    # Load temporal index for freshness-aware scoring
    TEMPORAL_BLEND_WEIGHT = 0.10
    tidx = None
    try:
        from lib.memory.temporal import TemporalIndex
        tidx = TemporalIndex()
    except (ImportError, Exception):
        pass

    for fpath in sorted(SHADOW_DIR.glob("*.md")):
        if fpath.name == "README.md":
            continue
        fm = extract_frontmatter(fpath)
        if not fm.get("id"):
            continue

        sid = fm["id"]
        title = fm.get("title", sid)
        synthesis = fm.get("synthesis", "")
        pointer_path = fm.get("pointer", {}).get("path", "")
        pinned = fm.get("score", {}).get("pinned", False)
        extraction_status = fm.get("extraction_status", "pending")
        doc_accesses = accesses.get(sid, [])

        act = compute_activation(doc_accesses, now)
        cent = compute_centrality(sid, dependencies)
        score = composite_score(act, pinned, cent)

        # Blend temporal decay into index score
        if tidx:
            tdoc = tidx.docs().get(sid)
            if tdoc:
                decay = tdoc.temporal_decay()
                score = (1 - TEMPORAL_BLEND_WEIGHT) * score + TEMPORAL_BLEND_WEIGHT * decay

        if synthesis:
            mark_synthesis(sid)

        preview = synthesis[:120].replace("\n", " ") + ("..." if len(synthesis) > 120 else "")
        pin_mark = " 📌" if pinned else ""
        gmif = fm.get("gmif", "")
        entries.append({
            "id": sid,
            "title": title,
            "preview": preview,
            "pointer": pointer_path,
            "score": score,
            "pin_mark": pin_mark,
            "gmif": gmif,
            "extraction_status": extraction_status,
        })

    entries.sort(key=lambda e: e["score"], reverse=True)

    # Keep ALL shadow docs in the index — the staleness check requires every id
    # to be present. An earlier hard cap (budget // TOKEN_ESTIMATE_PER_ENTRY)
    # silently dropped low-score docs once the doc count exceeded it, breaking
    # check_staleness (T268). Size enforcement lives in check(), on the
    # distribution — not here, and never by losing entries.
    max_entries = len(entries)

    lines = [
        "# AES Hot Index",
        "",
        "> Auto-generated by scripts/generate-index.py. Do not hand-edit.",
        f"> Generated: {now.isoformat()}",
        f"> Entries: {len(entries)} (~{TOKEN_ESTIMATE_PER_ENTRY} tokens/entry est.)",
        "",
        "<!-- INDEX_START -->",
        "",
        "| Shadow | GMIF | Score | Synthesis |",
        "|--------|------|-------|-----------|",
    ]
    for e in entries:
        gmif = e.get("gmif", "")
        lines.append(f"| **{e['id']}**{e['pin_mark']} — {e['title']} | {gmif} | {e['score']:.2f} | {e['preview']} |")

    lines.extend(["", "<!-- INDEX_END -->", ""])

    new_content = "\n".join(lines)

    # Only write if content changed (idempotency — make sleep twice = no git diff)
    # Strip timestamp line from comparison to avoid always-different checksums
    if INDEX_FILE.exists():
        old_lines = INDEX_FILE.read_text().split("\n")
        old_stripped = [l for l in old_lines if not l.startswith("> Generated:")]
        new_stripped = [l for l in lines if not l.startswith("> Generated:")]
        if old_stripped == new_stripped:
            print(f"INDEX.md unchanged ({len(entries)} entries)")
            return 0

    INDEX_FILE.write_text(new_content)
    print(f"INDEX.md generated: {len(entries)} entries")

    # Auto-generate token budget trace (P6)
    trace_script = AES_ROOT / "scripts" / "token-budget-trace.py"
    if trace_script.exists():
        import subprocess
        subprocess.run([sys.executable, str(trace_script)], check=False)

    return 0


def check_staleness() -> list[str]:
    """Check if INDEX.md is stale relative to shadow docs on disk."""
    warnings = []
    if not INDEX_FILE.exists():
        return [f"INDEX.md not found — run 'make index'"]
    gen_marker = None
    for line in INDEX_FILE.read_text().splitlines():
        if line.startswith("> Generated:"):
            gen_marker = line
            break
    if not gen_marker:
        return [f"Cannot determine INDEX.md generation time — missing 'Generated:' marker"]

    shadow_files = sorted(SHADOW_DIR.glob("*.md"))
    for fpath in shadow_files:
        if fpath.name == "README.md":
            continue
        fm = extract_frontmatter(fpath)
        if not fm.get("id"):
            continue
        # The index already has an entry for this shadow doc?
        # Check by looking for the shadow doc id in INDEX.md
        sid = fm["id"]
        if sid not in INDEX_FILE.read_text():
            warnings.append(f"  ⚠ Shadow doc {sid} ({fpath.name}) missing from INDEX.md")
    return warnings


def check():
    """Check INDEX.md: per-entry size distribution + staleness.

    The gate is on the DISTRIBUTION, not the total. An absolute total on a
    file that grows with the corpus is a fact, not a signal — it fired seven
    times against healthy growth and was raised seven times, never catching a
    defect (see lib/memory/config.py for the full reasoning).
    """
    if not INDEX_FILE.exists():
        print(f"INDEX_CHECK: {INDEX_FILE} not found — run 'make index' first")
        return 1

    from lib.memory.config import (
        deprecated_token_budget,
        resolve_max_doc_tokens,
        resolve_max_mean_tokens,
    )

    content = INDEX_FILE.read_text()

    # Per-entry sizes, measured on the lines that actually carry an entry.
    entry_tokens = []
    for line in content.splitlines():
        if SD_ENTRY_RE.search(line):
            entry_tokens.append(int(len(line.split()) * 1.3))

    status = 0
    if not entry_tokens:
        print("INDEX_CHECK: no index entries found — cannot size-check")
        status = 1
    else:
        max_doc = resolve_max_doc_tokens()
        max_mean = resolve_max_mean_tokens()
        mean = int(sum(entry_tokens) / len(entry_tokens))
        biggest = max(entry_tokens)
        total = int(len(content.split()) * 1.3)

        print(
            f"INDEX_CHECK: {len(entry_tokens)} entries, total ~{total} tokens, "
            f"mean {mean}/entry, largest {biggest} "
            f"(limits: mean<={max_mean}, any-entry<={max_doc})"
        )

        if mean > max_mean:
            print(
                f"INDEX_CHECK FAILED: mean entry size {mean} > {max_mean}. "
                f"That is systematic bloat — index entries are carrying content "
                f"instead of linking to it. The total may be fine; the shape is not."
            )
            status = 1
        if biggest > max_doc:
            print(
                f"INDEX_CHECK FAILED: an index entry is {biggest} tokens > "
                f"{max_doc}. One entry that large will dominate whatever context "
                f"loads the index."
            )
            status = 1
        if status == 0:
            print("INDEX_CHECK PASSED")

    stale_budget = deprecated_token_budget()
    if stale_budget is not None:
        print(
            f"INDEX_CHECK: warning — AES_INDEX_TOKEN_BUDGET={stale_budget} is "
            f"configured but gates nothing. The absolute total was replaced by "
            f"AES_INDEX_MAX_DOC_TOKENS / AES_INDEX_MAX_MEAN_TOKENS. Remove it."
        )

    staleness_warnings = check_staleness()
    for w in staleness_warnings:
        print(f"INDEX_CHECK: {w}")
        status = status or 2  # warning code

    return status


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        sys.exit(check())
    sys.exit(generate())
