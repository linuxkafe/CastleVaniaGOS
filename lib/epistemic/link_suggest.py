"""
Link discovery for the learn phase (T207).

Finds node pairs that share targets but lack direct edges — implicit
connections the graph doesn't represent. Outputs suggestions as a
markdown file for human review.
"""

import time
from pathlib import Path
from typing import List, Dict, Any

AES_ROOT = Path(__file__).resolve().parent.parent.parent
SUGGESTIONS_FILE = AES_ROOT / "aes" / "shadow" / "LINK-SUGGESTIONS.md"


def suggest_links(
    store,
    min_strength: int = 2,
    dry_run: bool = False,
) -> List[Dict[str, Any]]:
    """Find potential edges from shared-target analysis.

    Returns list of candidate edges with source, target, shared_targets, strength.
    If dry_run=False and candidates exist, writes LINK-SUGGESTIONS.md.
    """
    start = time.time()

    candidates = store.discover_links(min_shared_targets=min_strength)

    # Filter: skip pairs where both nodes come from same ticket
    filtered = []
    for c in candidates:
        if not _same_ticket(c["source"], c["target"]):
            filtered.append(c)

    elapsed_ms = round((time.time() - start) * 1000)

    if not dry_run and filtered:
        _write_suggestions_file(filtered, elapsed_ms)

    return filtered


def _same_ticket(id_a: str, id_b: str) -> bool:
    """Check if two IDs likely belong to the same ticket."""
    # Extract ticket prefix (e.g., "T199" from "T199-something")
    def ticket_prefix(nid: str) -> str:
        parts = nid.split("-")
        if parts and parts[0].startswith("T") and parts[0][1:].isdigit():
            return parts[0]
        return ""

    prefix_a = ticket_prefix(id_a)
    prefix_b = ticket_prefix(id_b)
    return bool(prefix_a and prefix_a == prefix_b)


def _write_suggestions_file(candidates: List[Dict], elapsed_ms: int) -> None:
    """Write LINK-SUGGESTIONS.md with candidate edges."""
    lines = [
        "---",
        "type: suggestions",
        "okf_version: 0.2",
        "ticket: link-discovery",
        "status: suggestions",
        f"generated_at: {time.strftime('%Y-%m-%dT%H:%M:%S%z')}",
        "---",
        "",
        "# Link Suggestions",
        "",
        f"Auto-generated by `link_suggest.py` — {len(candidates)} candidate(s) found in {elapsed_ms}ms.",
        "Review each suggestion and add edges to the appropriate DOT file if valid.",
        "",
        "| # | Source | Target | Shared Targets | Strength |",
        "|---|--------|--------|----------------|----------|",
    ]

    for i, c in enumerate(candidates, 1):
        shared = ", ".join(c["shared_targets"][:5])  # cap at 5
        if len(c["shared_targets"]) > 5:
            shared += f" (+{len(c['shared_targets']) - 5} more)"
        lines.append(f"| {i} | {c['source']} | {c['target']} | {shared} | {c['strength']} |")

    lines.extend([
        "",
        "## Next Steps",
        "",
        "1. Review each candidate — is this a real relationship?",
        "2. For valid links: add edge to the relevant DOT file in `aes/premises/`",
        "3. For invalid links: ignore (they won't be re-suggested if strength doesn't change)",
        "4. Re-run: `make link-suggest`",
        "",
    ])

    SUGGESTIONS_FILE.parent.mkdir(parents=True, exist_ok=True)
    SUGGESTIONS_FILE.write_text("\n".join(lines), encoding="utf-8")
